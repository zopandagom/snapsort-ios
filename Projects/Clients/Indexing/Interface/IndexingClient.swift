/// 보관함 이미지를 분류 파이프라인으로 분석해 저장소에 맞춰 두는 인덱서 (docs/ARCHITECTURE.md §4).
/// 다른 Client(PhotoLibrary·ImageAnalysis·PhotoStore·Classifier)를 조합한다.
/// 구현은 IndexingImpl, 테스트 대역은 IndexingTesting 에 있다.
public protocol IndexingClient: Sendable {
  /// 인덱싱을 시작하고 진행률을 보낸다. 보관함과 저장소를 비교해 새 이미지만 분석하고, 보관함에서 지워진 이미지의 결과는 지운다.
  /// 분석은 두 단계다: 1단계는 새 이미지를 모두 분류해 저장하고(OCR 대상은 OCR 대기로), 2단계는 대기 이미지를 최신순으로 OCR 해 바꿔 저장한다.
  /// 2단계에서 원본을 읽거나 OCR 하지 못한 이미지는 대기로 남아 다음 실행이나 전체 다시 비교 때 다시 시도한다.
  /// 2단계에서 기프티콘으로 분류한 이미지는 이미지 생성일과 주입한 달력으로 만료일·교환처를, 영수증으로 분류한 이미지는 읽은 줄로
  /// 가게·금액·통화·취소를, 쇼핑·대화·지도로 분류한 이미지는 읽은 줄로 쇼핑몰·브랜드·대화 앱·지역을 추출해 함께 저장한다(여럿이면 값을 함께).
  /// 저장된 기프티콘·영수증·캡처 묶음 중 지금 규칙 버전으로 추출하지 않은 것(저장소 이전 뒤, 규칙 버전을 올린 뒤)은 OCR 없이 저장된 줄로
  /// 소급 추출한다(기프티콘 → 영수증 → 캡처 묶음 순서, 대상은 따로라 한쪽의 실패가 다른 쪽을 멈추지 않는다).
  /// 소급은 진행률·`isFinished` 에 넣지 않아 `isFinished` 진행률 뒤에도 남아 있을 수 있고(`isFinished` 를 추출이 끝났다는 뜻으로 쓰지 않는다),
  /// 대상이 비면(다 마쳤거나 실패로 멈춤) 같은 값의 진행률을 기프티콘·영수증·캡처 묶음 각자 한 번 더 보낸다.
  /// 언어 모델을 쓸 수 있으면 2단계가 규칙 결과를 보강한다: 규칙 분류가 기타뿐인 이미지에 원문 근거가 있는 정보형 카테고리를 더하고,
  /// 기프티콘 추출 값의 빈 필드를 원문으로 확인된 모델 값으로 채운다. 보강을 마치지 않은 저장 기프티콘(모델을 못 쓴 때 저장, 보강 버전을 올린 뒤)은
  /// 2단계 뒤 저장된 줄로 소급 보강하고, 소급 추출과 같이 진행률에 넣지 않으며 대상이 비면 같은 값의 진행률을 한 번 더 보낸다.
  /// 모델을 쓸 수 없거나 모델이 실패해도 멈추지 않고 규칙 결과로 저장한다. 모델이 잇달아 실패하면 다음 전체 다시 비교까지 모델을 부르지 않는다.
  /// 2단계·소급 추출·소급 보강 도중 온 보관함 변경은 배치 경계에서 먼저 반영한다(새 이미지 1단계).
  /// 비교 기준은 지금 읽을 수 있는 이미지이므로, 제한 접근(`.limited`)이면 고르지 않은 이미지의 결과도 지운다.
  /// 화면 안내("선택한 사진만 분류합니다")와 같게 고른 사진만 분류하고, 다시 전체 접근을 주면 처음부터 분석한다.
  /// 처음 비교를 마친 뒤에도 보관함 변경을 계속 반영하므로, 받는 쪽이 구독을 끝내야(Task 취소) 멈춘다.
  /// 받는 쪽이 늦게 읽으면 지난 진행률은 버리고 가장 최근 값만 남긴다.
  /// 사진을 읽을 권한이 없으면(`PhotoAccessState.canRead` 거짓) 저장 결과를 그대로 두고 스트림을 끝낸다.
  /// 저장소를 읽거나 쓰지 못하면 멈추고 스트림을 끝낸다. 다음 `run()` 에서 저장된 데까지 건너뛰고 이어서 분석한다
  /// (1단계를 마친 이미지는 다시 분류하지 않고 2단계만 이어 한다).
  /// 단, 소급 추출·소급 보강(대상 조회·읽기·저장)만 실패하면 멈추지 않는다. 이번 실행에서는 그 소급만 멈추고 분류·글자 읽기는 이어 가며,
  /// 다음 실행이나 전체 다시 비교에서 소급을 다시 시도한다.
  func run() -> AsyncStream<IndexingProgress>
}
